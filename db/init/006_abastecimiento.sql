-- ---------------------------------------------------------------------------
-- Reloj de la demo: fecha de referencia compartida por la UI, la API y el evaluador.
-- Sin fila (o valor NULL) = fecha real. "Simular +N días" la mueve hacia adelante.
-- ---------------------------------------------------------------------------
CREATE TABLE config_demo (
    clave TEXT PRIMARY KEY,
    valor TEXT
);

CREATE FUNCTION fecha_referencia() RETURNS DATE
LANGUAGE sql STABLE AS $$
    SELECT COALESCE((SELECT valor::DATE FROM config_demo WHERE clave = 'fecha_referencia'), CURRENT_DATE)
$$;


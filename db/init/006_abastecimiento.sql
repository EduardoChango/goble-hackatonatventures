-- ---------------------------------------------------------------------------
-- Saldo real de medicación (receta vigente de cada paciente)
--   unidades_obtenidas = entregado por el IESS + comprado
--   fecha_agotamiento  = inicio de la receta + unidades_obtenidas / tomas por día
--   dias_restantes     = fecha_agotamiento - fecha_referencia()   (mínimo 0)
-- Supuestos: 1 tableta por toma y adherencia completa desde la fecha de la receta.
-- Debe dar lo mismo que abastecimiento/calculo.py (lo verifican las pruebas).
-- ---------------------------------------------------------------------------
CREATE VIEW v_saldo_medicacion AS
SELECT x.*,
       CASE
           WHEN x.sin_respuesta_iess              THEN 'sin_respuesta_iess'
           WHEN x.dias_restantes <= 0             THEN 'agotado'
           WHEN x.dias_restantes <= x.umbral_dias THEN 'por_agotarse'
           ELSE 'ok'
       END AS estado
FROM (
    SELECT i.paciente_id,
           i.visita_id,
           i.receta_item_id,
           i.nombre,
           i.dosis_mg,
           m.uid                                                     AS uid_medicina,
           m.concentracion,
           m.grupo,
           m.controlado,
           i.tomas_por_dia,
           i.dias                                                    AS dias_receta,
           i.visita_fecha                                            AS inicio,
           i.visita_fecha + i.dias                                   AS fin_tratamiento,
           i.recibido_iess,
           i.comprado,
           i.inventario                                              AS unidades_obtenidas,
           ref.hoy                                                   AS fecha_referencia,
           i.visita_fecha + i.inventario / i.tomas_por_dia           AS fecha_agotamiento,
           GREATEST(i.inventario - i.tomas_por_dia * GREATEST(ref.hoy - i.visita_fecha, 0), 0)
                                                                     AS saldo_unidades,
           GREATEST(i.visita_fecha + i.inventario / i.tomas_por_dia - ref.hoy, 0)
                                                                     AS dias_restantes,
           p.umbral_dias,
           (fr.visita_id IS NOT NULL)                                AS sin_respuesta_iess
    FROM v_inventario i
    JOIN v_visita_actual va  ON va.id = i.visita_id
    JOIN paciente p          ON p.id = i.paciente_id
    JOIN receta_item ri      ON ri.id = i.receta_item_id
    JOIN medicinas m         ON m.uid = ri.uid_medicina
    CROSS JOIN (SELECT fecha_referencia() AS hoy) ref
    LEFT JOIN v_falta_respuesta_iess fr ON fr.visita_id = i.visita_id
) x;

-- ---------------------------------------------------------------------------
-- Cuidadores: un cuidador puede tener varios pacientes y un paciente varios cuidadores
-- ---------------------------------------------------------------------------
CREATE TABLE cuidador (
    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    TEXT NOT NULL,
    email     TEXT NOT NULL,
    telefono  TEXT,
    lat       NUMERIC(10, 7) NOT NULL,     -- desde dónde sale a comprar (para el ranking de farmacias)
    lng       NUMERIC(10, 7) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX cuidador_email_idx ON cuidador (lower(email));

CREATE TABLE paciente_cuidador (
    paciente_id INT  NOT NULL REFERENCES paciente (id) ON DELETE CASCADE,
    cuidador_id INT  NOT NULL REFERENCES cuidador (id) ON DELETE CASCADE,
    rol         TEXT NOT NULL DEFAULT 'principal' CHECK (rol IN ('principal', 'apoyo')),
    parentesco  TEXT,                          -- "Hija", "Enfermera", ...
    PRIMARY KEY (paciente_id, cuidador_id)
);


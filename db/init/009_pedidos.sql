-- =============================================================================
-- Mock de Farmaenlace: su propio esquema (en la realidad es otro sistema).
-- Recibe la demanda prevista y los pedidos, reserva stock y responde por callback.
-- =============================================================================
CREATE SCHEMA farmaenlace;

CREATE TABLE farmaenlace.demanda (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id       TEXT,
    farmacia_id     INT  NOT NULL,
    uid_medicina    TEXT NOT NULL,
    nombre          TEXT NOT NULL,
    cantidad        INT  NOT NULL,
    fecha_necesidad DATE,
    recibido_en     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE farmaenlace.pedido (
    ref             TEXT PRIMARY KEY,           -- FE-PED-000001
    pedido_origen   INT  NOT NULL,              -- id del pedido en el módulo
    farmacia_id     INT  NOT NULL,
    modo            TEXT NOT NULL,
    estado          TEXT NOT NULL,
    items           JSONB NOT NULL,
    cliente         JSONB NOT NULL,             -- nombre, dirección, teléfono (solo con consentimiento)
    eta             TIMESTAMPTZ,
    motivo          TEXT,
    creado_en       TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE SEQUENCE farmaenlace.pedido_ref_seq;
